"""
cClyptus.AI SAP BRIM - Safe Rollback and Deactivation Procedure.
Restores legacy pipeline state and safeguards knowledge-base integrity.

Actions performed:
1. Verifies/enforces REPO_SOURCE_ENABLED=false and MULTI_SOURCE_COMPARE_ENABLED=false.
2. Safeguards production knowledge base by verifying its chunk count is unchanged.
3. Optionally purges isolated github_repo_chunks table if requested via --purge-repo-chunks.
4. Verifies that legacy hybrid retrieval and baseline responses are 100% functional.
"""

import sys
import argparse
import logging
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent.parent
if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

from backend.app.database import SessionLocal, engine
from backend.app.config import settings
from backend.app.models.chunk import DocumentChunk
from backend.app.models.repo_chunk import GitHubRepoChunk
from backend.app.services.rag_service import rag_service

logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")
logger = logging.getLogger("rollback_procedure")


def execute_rollback(purge_repo_records: bool = False) -> bool:
    logger.info("================================================================================")
    logger.info("EXECUTING SAFE ROLLBACK & VERIFICATION FOR GITHUB RETRIEVAL PIPELINE")
    logger.info("================================================================================")

    # 1. Feature Flag Audit
    logger.info("Step 1: Checking feature flag configuration...")
    repo_flag = getattr(settings, "REPO_SOURCE_ENABLED", False)
    compare_flag = getattr(settings, "MULTI_SOURCE_COMPARE_ENABLED", False)
    
    if repo_flag or compare_flag:
        logger.warning(f"Feature flags currently active: REPO_SOURCE_ENABLED={repo_flag}, MULTI_SOURCE_COMPARE_ENABLED={compare_flag}")
        logger.warning("Please ensure environment variables REPO_SOURCE_ENABLED=false and MULTI_SOURCE_COMPARE_ENABLED=false in .env or deployment config.")
    else:
        logger.info("Feature flags confirmed DISABLED (REPO_SOURCE_ENABLED=false, MULTI_SOURCE_COMPARE_ENABLED=false).")

    # 2. Database Integrity Verification
    logger.info("Step 2: Auditing production knowledge base integrity...")
    db = SessionLocal()
    try:
        kb_count_before = db.query(DocumentChunk).count()
        logger.info(f"Production document_chunks count before rollback actions: {kb_count_before}")
        if kb_count_before == 0:
            logger.error("CRITICAL: Production knowledge base contains no document chunks.")
            return False

        # 3. Repository Record Management
        repo_count = db.query(GitHubRepoChunk).count()
        logger.info(f"Isolated github_repo_chunks count: {repo_count}")

        if purge_repo_records:
            logger.info("Purging records from isolated github_repo_chunks table...")
            deleted = db.query(GitHubRepoChunk).delete()
            db.commit()
            logger.info(f"Safely purged {deleted} records from github_repo_chunks.")
        else:
            logger.info("Preserving github_repo_chunks table for audit (table remains isolated and inactive).")

        kb_count_after = db.query(DocumentChunk).count()
        if kb_count_after != kb_count_before:
            logger.error(
                "CRITICAL: Knowledge-base chunk count changed during repository rollback (%s -> %s).",
                kb_count_before,
                kb_count_after,
            )
            return False
        logger.info("Production knowledge base is intact and untouched.")

        # 4. Smoke Test Legacy Retrieval
        logger.info("Step 3: Running smoke test on legacy retrieval pipeline...")
        test_query = "What is SAP BRIM and its primary components?"
        result = rag_service.query(test_query, db=db)

        if not result or not result.get("answer"):
            logger.error("Smoke test failed: no answer generated by legacy pipeline.")
            return False

        logger.info("Smoke test passed successfully!")
        logger.info(f"Winning source: {result.get('selected_source', result.get('source_type'))}")
        logger.info(f"Grounding score: {result.get('grounding_score', result.get('grounded_score'))}")
        logger.info(f"Citations count: {len(result.get('citations', []))}")
        logger.info("Legacy pipeline is 100% operational.")

    finally:
        db.close()

    logger.info("================================================================================")
    logger.info("ROLLBACK AUDIT COMPLETE: ALL CHECKS PASSED.")
    logger.info("================================================================================")
    return True


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Rollback GitHub repository retrieval and verify legacy stability.")
    parser.add_argument("--purge-repo-chunks", action="store_true", help="Purge records from github_repo_chunks table.")
    args = parser.parse_args()

    success = execute_rollback(purge_repo_records=args.purge_repo_chunks)
    sys.exit(0 if success else 1)
