import { writeFile, mkdir } from 'node:fs/promises';
import { connect, delay } from './cdp.mjs';
await mkdir('performance/results', { recursive: true });
const label = process.argv[2] ?? 'diagnostic';
const cdp = await connect();
await cdp.send('Page.enable');
await cdp.send('Network.enable');
await cdp.send('Network.setCacheDisabled', { cacheDisabled:true });
await cdp.send('Network.clearBrowserCache');
await cdp.send('Emulation.setDeviceMetricsOverride', {width:1440,height:900,deviceScaleFactor:1,mobile:false});
await cdp.send('DOM.enable');
await cdp.send('CSS.enable');
await cdp.send('CSS.startRuleUsageTracking');
await cdp.send('Profiler.enable');
await cdp.send('Profiler.startPreciseCoverage', { callCount:true, detailed:true });
const events = [];
cdp.on('Tracing.dataCollected', ({value})=>events.push(...value));
const completed = new Promise(resolve=>cdp.on('Tracing.tracingComplete',resolve));
await cdp.send('Tracing.start', { categories:'devtools.timeline,blink.user_timing,loading,v8,disabled-by-default-devtools.timeline', options:'record-as-much-as-possible' });
await cdp.send('Page.navigate', {url:'http://127.0.0.1:4173/'});
await delay(3000);
const coverage = await cdp.send('Profiler.takePreciseCoverage');
const css = await cdp.send('CSS.stopRuleUsageTracking');
await cdp.send('Tracing.end');
await completed;
await writeFile(`performance/results/${label}-trace.json`, JSON.stringify({traceEvents:events}));
await writeFile(`performance/results/${label}-coverage.json`, JSON.stringify({js:coverage.result,css:css.ruleUsage},null,2));
console.log('Longest main-thread events',events.filter(e=>e.ph==='X'&&e.dur&&['Layout','UpdateLayoutTree','FunctionCall','EvaluateScript','Paint'].includes(e.name)).sort((a,b)=>b.dur-a.dur).slice(0,12).map(e=>({name:e.name,ms:e.dur/1000,args:e.args})));
console.log('Scripts',coverage.result.filter(x=>x.url.includes('/assets/')).map(s=>({url:s.url,usedFunctions:s.functions.filter(f=>f.ranges.some(r=>r.count)).length,totalFunctions:s.functions.length})));
console.log('CSS rules', {total:css.ruleUsage.length,used:css.ruleUsage.filter(r=>r.used).length});
await cdp.close();
